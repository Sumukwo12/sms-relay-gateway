defmodule Backend.MixProject do
  use Mix.Project

  def project do
    [
      app: :backend,
      version: "0.1.0",
      elixir: "~> 1.17",
      elixirc_paths: elixirc_paths(Mix.env()),
      start_permanent: Mix.env() == :prod,
      aliases: aliases(),
      deps: deps(),
      compilers: [:phoenix_live_view] ++ Mix.compilers(),
      listeners: [Phoenix.CodeReloader]
    ]
  end

  # Configuration for the OTP application.
  #
  # Type `mix help compile.app` for more information.
  def application do
    [
      mod: {Backend.Application, []},
      extra_applications: [:logger, :runtime_tools]
    ]
  end

  def cli do
    [
      preferred_envs: [precommit: :test]
    ]
  end

  # Specifies which paths to compile per environment.
  defp elixirc_paths(:test), do: ["lib", "test/support"]
  defp elixirc_paths(_), do: ["lib"]

  # Specifies your project dependencies.
  #
  # Type `mix help deps` for examples and options.
  defp deps do
    [
      {:phoenix, "~> 1.8.15"},
      {:phoenix_html, "~> 4.1"},
      {:phoenix_live_reload, "~> 1.2", only: :dev},
      {:phoenix_live_view, "~> 1.2.0"},
      {:lazy_html, ">= 0.1.0", only: :test},
      {:telemetry_metrics, "~> 1.0"},
      {:telemetry_poller, "~> 1.0"},
      {:jason, "~> 1.2"},
      {:dns_cluster, "~> 0.2.0"},
      {:bandit, "~> 1.5"},
      # TTL-based code storage + rate limiting
      {:cachex, "~> 3.6"},
      # CORS support for Next.js frontend
      {:cors_plug, "~> 3.0"},
      # HTTP client for Android SMS gateway adapter
      {:req, "~> 0.5"}
    ] ++ modem_deps()
  end

  # GSM modem serial communication. circuits_uart compiles a C port program,
  # so it needs make + gcc; only pull it in when the real modem is used.
  defp modem_deps do
    if Mix.env() == :prod or System.get_env("MODEM_ADAPTER") == "uart" do
      [{:circuits_uart, "~> 1.5"}]
    else
      []
    end
  end

  # Aliases are shortcuts or tasks specific to the current project.
  # For example, to install project dependencies and perform other setup tasks, run:
  #
  #     $ mix setup
  #
  # See the documentation for `Mix` for more info on aliases.
  defp aliases do
    [
      setup: ["deps.get"],
      # Do not run "deps.unlock --unused" because optional dependencies
      # like :circuits_uart are only loaded in prod or when MODEM_ADAPTER=uart.
      precommit: ["compile --warnings-as-errors", "format", "test"]
    ]
  end
end
